//! `cargo xtask env`: `docs/env.md`, every environment switch the code
//! reads, generated from the source.
//!
//! A switch is a string literal naming a `VICTORY_` variable in a Rust
//! file. The table says where each is read and whether the other docs
//! mention it; `victory-core` reads the names back to warn about a set
//! variable that nothing reads (a typo, or a switch that was removed).
//! `cargo xtask env --check` fails on a stale table; the test only warns
//! (unless `VICTORY_STRICT_TESTS=1`).

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use anyhow::{Context, Result, bail};

/// Where the table lives, relative to the workspace root.
pub const DOC: &str = "docs/env.md";

const PREFIX: &str = "VICTORY_";

/// Each switch, with the files (workspace-relative) whose Rust source
/// names it in a string literal.
fn switches(root: &Path, files: &[String]) -> Result<BTreeMap<String, BTreeSet<String>>> {
    let quoted = format!("\"{PREFIX}");
    let mut found: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    for path in files.iter().filter(|p| p.ends_with(".rs")) {
        let Ok(text) = std::fs::read_to_string(root.join(path)) else {
            continue;
        };
        let mut rest = text.as_str();
        while let Some(at) = rest.find(&quoted) {
            let tail = &rest[at + 1..];
            let len = tail
                .find(|c: char| !(c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_'))
                .unwrap_or(tail.len());
            // Only a whole literal (the closing quote right after the
            // name), not a prefix or a message that merely starts with one.
            if tail[len..].starts_with('"') && len > PREFIX.len() {
                found
                    .entry(tail[..len].to_string())
                    .or_default()
                    .insert(path.clone());
            }
            rest = &tail[len..];
        }
    }
    Ok(found)
}

/// Switches the hand-written docs mention: the README, `docs/` (but this
/// table) and the example config.
fn documented(root: &Path, files: &[String]) -> BTreeSet<String> {
    let mut names = BTreeSet::new();
    let docs = files.iter().filter(|p| {
        (p.ends_with(".md") && *p != DOC && (p.starts_with("docs/") || !p.contains('/')))
            || *p == "victory.example.toml"
    });
    for path in docs {
        let Ok(text) = std::fs::read_to_string(root.join(path)) else {
            continue;
        };
        let mut rest = text.as_str();
        while let Some(at) = rest.find(PREFIX) {
            let tail = &rest[at..];
            let len = tail
                .find(|c: char| !(c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_'))
                .unwrap_or(tail.len());
            names.insert(tail[..len].to_string());
            rest = &tail[len..];
        }
    }
    names
}

/// The text of `docs/env.md`.
pub fn render(root: &Path) -> Result<String> {
    let files = crate::policy::list_files(root, false)?;
    let found = switches(root, &files)?;
    let docs = documented(root, &files);
    let mut out = String::from(
        "# Environment switches\n\
         \n\
         Every `VICTORY_*` variable the code reads, generated by `cargo xtask env`\n\
         from the source; do not edit by hand. A test fails when it is out of date.\n\
         \"Documented\" says whether the README, another page in `docs/` or\n\
         `victory.example.toml` describes it. At startup a set `VICTORY_*`\n\
         variable missing from this list is reported as read by nothing.\n\
         \n",
    );
    let described = found.keys().filter(|n| docs.contains(*n)).count();
    out.push_str(&format!(
        "{} switches, {} of them documented elsewhere.\n\n",
        found.len(),
        described
    ));
    out.push_str("| Variable | Read in | Documented |\n|---|---|---|\n");
    for (name, paths) in &found {
        let paths: Vec<String> = paths.iter().map(|p| format!("`{p}`")).collect();
        let doc = if docs.contains(name) { "yes" } else { "" };
        out.push_str(&format!("| `{name}` | {} | {doc} |\n", paths.join(", ")));
    }
    Ok(out)
}

pub fn run(root: &Path, check: bool) -> Result<()> {
    let text = render(root)?;
    let path = root.join(DOC);
    if check {
        // (A Windows checkout may have turned the newlines into CRLF.)
        let now = std::fs::read_to_string(&path)
            .unwrap_or_default()
            .replace("\r\n", "\n");
        if now != text {
            bail!("{DOC} is out of date: run `cargo xtask env`");
        }
        println!("{DOC} is current");
        return Ok(());
    }
    std::fs::write(&path, text).with_context(|| format!("writing {DOC}"))?;
    println!("wrote {DOC}");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A stale table is a warning (a PR adding a switch should not go red
    /// over it), and a failure with `VICTORY_STRICT_TESTS=1`.
    #[test]
    fn env_table_is_current() {
        let root = crate::workspace_root();
        let now = std::fs::read_to_string(root.join(DOC))
            .unwrap_or_default()
            .replace("\r\n", "\n");
        if now == render(&root).unwrap() {
            return;
        }
        let strict = std::env::var("VICTORY_STRICT_TESTS").is_ok_and(|v| v == "1");
        assert!(
            !strict,
            "{DOC} is out of date: run `cargo xtask env` and commit it"
        );
        eprintln!("warning: {DOC} is out of date: run `cargo xtask env` and commit it");
    }

    #[test]
    fn only_whole_literals_count() {
        let dir = tempfile_dir();
        let src = format!(
            "let a = std::env::var(\"{p}ONE\");\nlet b = \"{p}TWO is set\";\nlet c = \"{p}\";\n",
            p = PREFIX
        );
        std::fs::write(dir.join("a.rs"), src).unwrap();
        let found = switches(&dir, &["a.rs".to_string()]).unwrap();
        assert_eq!(found.keys().collect::<Vec<_>>(), [&format!("{PREFIX}ONE")]);
        std::fs::remove_dir_all(dir).unwrap();
    }

    fn tempfile_dir() -> std::path::PathBuf {
        let dir = std::env::temp_dir().join(format!("xtask-env-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }
}
